# Example 1: Using triple quotes
my_string1='''
    Now so high
        Now so low
            I am swing I am swing'''

print(my_string1)
# Example 2: Using parentheses and a single/double quotes
my_string2=(
    "I am learning Python\n"
    "I am learning React\n"
    "I am learning Java"
)

print(my_string2)

# Example 3: Using \
my_string3="I am Here \n"\
    "I am there \n"\
    "He is here and here"
print(my_string3)


